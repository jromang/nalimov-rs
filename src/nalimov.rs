use std::ffi::{c_char, c_int, CStr};
use std::sync::OnceLock as FfiLock;

static GLOBAL_PROBER: FfiLock<NalimovProber> = FfiLock::new();

/// Initialize Nalimov tablebases from a directory path (C string).
/// Returns 1 on success, 0 on failure.
#[unsafe(no_mangle)]
pub extern "C" fn rs_nalimov_init(path: *const c_char) -> c_int {
    if path.is_null() {
        return 0;
    }
    let path_str = match unsafe { CStr::from_ptr(path) }.to_str() {
        Ok(s) => s,
        Err(_) => return 0,
    };
    match GLOBAL_PROBER.set(match NalimovProber::new(&[path_str], 256) {
        Ok(p) => p,
        Err(_) => return 0,
    }) {
        Ok(()) => 1,
        Err(_) => 1, // already initialized
    }
}

/// Probe a position. Returns 1 on success (score written to out_score), 0 on failure.
/// Score > 0 = side to move wins, < 0 = side to move loses, 0 = draw.
#[unsafe(no_mangle)]
pub extern "C" fn rs_nalimov_probe(
    white: u64,
    black: u64,
    kings: u64,
    queens: u64,
    rooks: u64,
    bishops: u64,
    knights: u64,
    pawns: u64,
    wtm: c_int,
    ep_square: u8,
    out_score: *mut c_int,
) -> c_int {
    let prober = match GLOBAL_PROBER.get() {
        Some(p) => p,
        None => return 0,
    };
    let result = prober.probe(
        white, black, kings, queens, rooks, bishops, knights, pawns,
        wtm != 0, ep_square,
    );
    match result {
        Ok(NalimovResult::Win { plies }) => {
            if !out_score.is_null() {
                unsafe { *out_score = plies as c_int; }
            }
            1
        }
        Ok(NalimovResult::Loss { plies }) => {
            if !out_score.is_null() {
                unsafe { *out_score = -(plies as c_int); }
            }
            1
        }
        Ok(NalimovResult::Draw) => {
            if !out_score.is_null() {
                unsafe { *out_score = 0; }
            }
            1
        }
        Err(_) => 0,
    }
}

