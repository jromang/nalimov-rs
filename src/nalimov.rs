/// TEnumerate1::Index — enumerate 2 kings and 1 piece.
/// piw1: piece type index (0-5), f_pawns: whether pawns present, f_invert: black pawn inversion
fn enumerate1(
    piw1: usize,
    f_pawns: bool,
    f_invert: bool,
    mut sqwk: u32,
    mut sqw1: u32,
    mut sqbk: u32,
) -> u32 {
    let e = get_enumerations();

    // For black pawn invert the board
    if piw1 <= X_PIECE_PAWN && f_invert {
        sqwk = reflect_x(sqwk);
        sqw1 = reflect_x(sqw1);
        sqbk = reflect_x(sqbk);
    }

    // Get enumerated square
    let ind = e.sq_piece[piw1][(sqbk as usize) * 64 + (sqw1 as usize)];
    if ind == 0xFF {
        return INF_SINGLE;
    }
    let mut ind = ind as u32;

    // Get enumerated position of both kings
    let ul_kings = if f_pawns {
        let v = get_half_kings()[(sqwk * 64 + sqbk) as usize];
        if v == INF {
            return INF_SINGLE;
        }
        v as u32
    } else {
        let v = get_tri_kings()[(sqwk * 64 + sqbk) as usize];
        if v == INF {
            return INF_SINGLE;
        }
        v as u32
    };

    // Can we remove one extra square?
    if piw1 > X_PIECE_KNIGHT
        || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
    {
        ind -= (sqw1 > sqwk) as u32;
    }

    // Add enumerated square to the # of preceding positions
    ind + if f_pawns {
        e.single_pawn[piw1][ul_kings as usize]
    } else {
        e.single_pawnless[piw1][ul_kings as usize]
    }
}

/// TEnumerate2::Index — enumerate 2 kings and 2 pieces.
fn enumerate2(
    piw1: usize,
    piw2: usize,
    f_pawns: bool,
    f_invert: bool,
    mut sqwk: u32,
    mut sqw1: u32,
    mut sqw2: u32,
    mut sqbk: u32,
) -> u32 {
    let e = get_enumerations();

    if piw2 <= X_PIECE_PAWN && f_invert {
        sqwk = reflect_x(sqwk);
        sqw1 = reflect_x(sqw1);
        sqw2 = reflect_x(sqw2);
        sqbk = reflect_x(sqbk);
    }

    if piw1 == piw2 {
        sort2(&mut sqw1, &mut sqw2);
    }

    let ind1_raw = e.sq_piece[piw1][(sqbk as usize) * 64 + (sqw1 as usize)];
    let ind2_raw = e.sq_piece[piw2][(sqbk as usize) * 64 + (sqw2 as usize)];
    if ind1_raw == 0xFF || ind2_raw == 0xFF {
        return INF_PAIR;
    }
    let mut ind1 = ind1_raw as u32;
    let mut ind2 = ind2_raw as u32;

    let ul_kings = if f_pawns {
        let v = get_half_kings()[(sqwk * 64 + sqbk) as usize];
        if v == INF {
            return INF_PAIR;
        }
        v as u32
    } else {
        let v = get_tri_kings()[(sqwk * 64 + sqbk) as usize];
        if v == INF {
            return INF_PAIR;
        }
        v as u32
    };

    let offset = if f_pawns {
        e.pair_pawn[piw1][piw2][ul_kings as usize]
    } else {
        e.pair_pawnless[piw1][piw2][ul_kings as usize]
    };

    if piw1 == piw2 {
        // Same piece: can we remove extra square?
        if piw1 > X_PIECE_KNIGHT
            || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            ind1 -= (sqw1 > sqwk) as u32;
            ind2 -= (sqw2 > sqwk) as u32;
        }
        ind2 * (ind2 - 1) / 2 + ind1 + offset
    } else {
        // Different pieces
        if piw1 > X_PIECE_KNIGHT
            || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            ind1 -= (sqw1 > sqwk) as u32;
        }
        let mut c_ind2 = e.c_legal[piw2][sqbk as usize] as u32;
        if piw2 > X_PIECE_KNIGHT
            || e.sq_piece[piw2][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            c_ind2 -= 1;
            ind2 -= (sqw2 > sqwk) as u32;
        }
        c_ind2 * ind1 + ind2 + offset
    }
}

/// TEnumerate3::Index — enumerate 2 kings and 3 pieces.
#[allow(clippy::too_many_arguments)]
fn enumerate3(
    piw1: usize,
    piw2: usize,
    piw3: usize,
    f_pawns: bool,
    f_invert: bool,
    mut sqwk: u32,
    mut sqw1: u32,
    mut sqw2: u32,
    mut sqw3: u32,
    mut sqbk: u32,
) -> u32 {
    let e = get_enumerations();

    if piw3 <= X_PIECE_PAWN && f_invert {
        sqwk = reflect_x(sqwk);
        sqw1 = reflect_x(sqw1);
        sqw2 = reflect_x(sqw2);
        sqw3 = reflect_x(sqw3);
        sqbk = reflect_x(sqbk);
    }

    // Sort pieces
    if piw1 == piw2 && piw1 == piw3 {
        sort3(&mut sqw1, &mut sqw2, &mut sqw3);
    } else if piw1 == piw2 {
        sort2(&mut sqw1, &mut sqw2);
    } else if piw2 == piw3 {
        sort2(&mut sqw2, &mut sqw3);
    }

    let i1 = e.sq_piece[piw1][(sqbk as usize) * 64 + (sqw1 as usize)];
    let i2 = e.sq_piece[piw2][(sqbk as usize) * 64 + (sqw2 as usize)];
    let i3 = e.sq_piece[piw3][(sqbk as usize) * 64 + (sqw3 as usize)];
    if i1 == 0xFF || i2 == 0xFF || i3 == 0xFF {
        return INF_TRIPLE;
    }
    let mut ind1 = i1 as u32;
    let mut ind2 = i2 as u32;
    let mut ind3 = i3 as u32;

    let ul_kings = if f_pawns {
        let v = get_half_kings()[(sqwk * 64 + sqbk) as usize];
        if v == INF {
            return INF_TRIPLE;
        }
        v as u32
    } else {
        let v = get_tri_kings()[(sqwk * 64 + sqbk) as usize];
        if v == INF {
            return INF_TRIPLE;
        }
        v as u32
    };

    let offset = if f_pawns {
        e.triple_pawn[piw1][piw2][piw3][ul_kings as usize]
    } else {
        e.triple_pawnless[piw1][piw2][piw3][ul_kings as usize]
    };

    if piw1 == piw2 && piw2 == piw3 {
        if piw1 > X_PIECE_KNIGHT
            || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            ind1 -= (sqw1 > sqwk) as u32;
            ind2 -= (sqw2 > sqwk) as u32;
            ind3 -= (sqw3 > sqwk) as u32;
        }
        ind3 * (ind3 - 1) * (ind3 - 2) / 6 + ind2 * (ind2 - 1) / 2 + ind1 + offset
    } else if piw1 == piw2 {
        if piw1 > X_PIECE_KNIGHT
            || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            ind1 -= (sqw1 > sqwk) as u32;
            ind2 -= (sqw2 > sqwk) as u32;
        }
        let mut c_ind3 = e.c_legal[piw3][sqbk as usize] as u32;
        if piw3 > X_PIECE_KNIGHT
            || e.sq_piece[piw3][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            c_ind3 -= 1;
            ind3 -= (sqw3 > sqwk) as u32;
        }
        (ind2 * (ind2 - 1) / 2 + ind1) * c_ind3 + ind3 + offset
    } else if piw2 == piw3 {
        if piw2 > X_PIECE_KNIGHT
            || e.sq_piece[piw2][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            ind2 -= (sqw2 > sqwk) as u32;
            ind3 -= (sqw3 > sqwk) as u32;
        }
        let mut c_ind1 = e.c_legal[piw1][sqbk as usize] as u32;
        if piw1 > X_PIECE_KNIGHT
            || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            c_ind1 -= 1;
            ind1 -= (sqw1 > sqwk) as u32;
        }
        (ind3 * (ind3 - 1) / 2 + ind2) * c_ind1 + ind1 + offset
    } else {
        if piw1 > X_PIECE_KNIGHT
            || e.sq_piece[piw1][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            ind1 -= (sqw1 > sqwk) as u32;
        }
        let mut c_ind2 = e.c_legal[piw2][sqbk as usize] as u32;
        if piw2 > X_PIECE_KNIGHT
            || e.sq_piece[piw2][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            c_ind2 -= 1;
            ind2 -= (sqw2 > sqwk) as u32;
        }
        let mut c_ind3 = e.c_legal[piw3][sqbk as usize] as u32;
        if piw3 > X_PIECE_KNIGHT
            || e.sq_piece[piw3][(sqbk as usize) * 64 + (sqwk as usize)] != 0xFF
        {
            c_ind3 -= 1;
            ind3 -= (sqw3 > sqwk) as u32;
        }
        c_ind3 * (c_ind2 * ind1 + ind2) + ind3 + offset
    }
}

