#[inline]
fn sort2(a: &mut u32, b: &mut u32) {
    if *a > *b {
        std::mem::swap(a, b);
    }
}

#[inline]
fn sort3(a: &mut u32, b: &mut u32, c: &mut u32) {
    sort2(a, b);
    sort2(b, c);
    sort2(a, b);
}

