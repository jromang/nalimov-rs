/// Translate VInitSquaresTable from egtb.cpp
fn v_init_squares_table(pi: usize, sq_piece: &mut [u8; 64 * 64], c_legal: &mut [u8; 64]) {
    sq_piece.fill(0xFF);

    let sq_lo: usize = if pi <= X_PIECE_PAWN { 8 } else { 0 };
    let sq_hi: usize = if pi <= X_PIECE_PAWN { 56 } else { 64 };

    for sq_king in 0u32..64 {
        let mut i_piece: u8 = 0;
        for sq in sq_lo..sq_hi {
            let sq = sq as u32;
            if sq == sq_king {
                continue;
            }
            let skip = match pi {
                X_PIECE_PAWN => {
                    // Pawn attacks diagonally forward (from white's perspective, toward higher ranks)
                    (tb_column(sq) != 0 && sq_king == sq + 7)
                        || (tb_column(sq) != 7 && sq_king == sq + 9)
                }
                X_PIECE_KNIGHT => {
                    (tb_row(sq) >= 2 && tb_column(sq) >= 1 && sq_king == sq.wrapping_sub(17))
                        || (tb_row(sq) >= 2
                            && tb_column(sq) <= 6
                            && sq_king == sq.wrapping_sub(15))
                        || (tb_row(sq) >= 1
                            && tb_column(sq) >= 2
                            && sq_king == sq.wrapping_sub(10))
                        || (tb_row(sq) >= 1
                            && tb_column(sq) <= 5
                            && sq_king == sq.wrapping_sub(6))
                        || (tb_row(sq) <= 6 && tb_column(sq) >= 2 && sq_king == sq + 6)
                        || (tb_row(sq) <= 6 && tb_column(sq) <= 5 && sq_king == sq + 10)
                        || (tb_row(sq) <= 5 && tb_column(sq) >= 1 && sq_king == sq + 15)
                        || (tb_row(sq) <= 5 && tb_column(sq) <= 6 && sq_king == sq + 17)
                }
                X_PIECE_BISHOP => {
                    (tb_row(sq) != 0
                        && tb_column(sq) != 0
                        && sq_king == sq.wrapping_sub(9))
                        || (tb_row(sq) != 0
                            && tb_column(sq) != 7
                            && sq_king == sq.wrapping_sub(7))
                        || (tb_row(sq) != 7 && tb_column(sq) != 0 && sq_king == sq + 7)
                        || (tb_row(sq) != 7 && tb_column(sq) != 7 && sq_king == sq + 9)
                }
                X_PIECE_ROOK => {
                    (tb_column(sq) != 0 && sq_king == sq.wrapping_sub(1))
                        || (tb_column(sq) != 7 && sq_king == sq + 1)
                        || (tb_row(sq) != 0 && sq_king == sq.wrapping_sub(8))
                        || (tb_row(sq) != 7 && sq_king == sq + 8)
                }
                X_PIECE_QUEEN => {
                    (tb_column(sq) != 0 && sq_king == sq.wrapping_sub(1))
                        || (tb_column(sq) != 7 && sq_king == sq + 1)
                        || (tb_row(sq) != 0 && sq_king == sq.wrapping_sub(8))
                        || (tb_row(sq) != 7 && sq_king == sq + 8)
                        || (tb_row(sq) != 0
                            && tb_column(sq) != 0
                            && sq_king == sq.wrapping_sub(9))
                        || (tb_row(sq) != 0
                            && tb_column(sq) != 7
                            && sq_king == sq.wrapping_sub(7))
                        || (tb_row(sq) != 7 && tb_column(sq) != 0 && sq_king == sq + 7)
                        || (tb_row(sq) != 7 && tb_column(sq) != 7 && sq_king == sq + 9)
                }
                _ => false, // x_pieceNone: no attack exclusions, just rank restriction
            };
            if skip {
                continue;
            }
            sq_piece[(sq_king as usize) * 64 + (sq as usize)] = i_piece;
            i_piece += 1;
        }
        c_legal[sq_king as usize] = i_piece;
    }
}

fn v_init_single(
    prg_index: &mut [u32],
    prgs_kings: &[i16; 4096],
    prgc_legal: &[u8; 64],
    prgsq_piece: &[u8; 64 * 64],
    pc_enumeration: &mut u32,
) {
    let mut i_index: u32 = 0;
    for sq_king1 in 0u32..64 {
        for sq_king2 in 0u32..64 {
            let king_val = prgs_kings[(sq_king1 * 64 + sq_king2) as usize];
            if king_val != INF {
                let idx = king_val as usize;
                prg_index[idx] = i_index;
                let c = prgc_legal[sq_king2 as usize] as u32;
                let wk_legal =
                    prgsq_piece[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF;
                i_index += c - wk_legal as u32;
            }
        }
    }
    *pc_enumeration = i_index;
}

fn v_init_pair(
    prg_index: &mut [u32],
    prgs_kings: &[i16; 4096],
    prgc_legal1: &[u8; 64],
    prgsq_piece1: &[u8; 64 * 64],
    pi1: usize,
    prgc_legal2: &[u8; 64],
    prgsq_piece2: &[u8; 64 * 64],
    pi2: usize,
    pc_enumeration: &mut u32,
) {
    let mut i_index: u32 = 0;
    for sq_king1 in 0u32..64 {
        for sq_king2 in 0u32..64 {
            let king_val = prgs_kings[(sq_king1 * 64 + sq_king2) as usize];
            if king_val != INF {
                let idx = king_val as usize;
                prg_index[idx] = i_index;
                let c1 = prgc_legal1[sq_king2 as usize] as u32
                    - (prgsq_piece1[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                        as u32;
                if pi1 == pi2 {
                    // Same piece type: pointer equality in C++ maps to index equality
                    i_index += c1 * (c1 - 1) / 2;
                } else {
                    let c2 = prgc_legal2[sq_king2 as usize] as u32
                        - (prgsq_piece2[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                            as u32;
                    i_index += c1 * c2;
                }
            }
        }
    }
    *pc_enumeration = i_index;
}

#[allow(clippy::too_many_arguments)]
fn v_init_triple(
    prg_index: &mut [u32],
    prgs_kings: &[i16; 4096],
    prgc_legal1: &[u8; 64],
    prgsq_piece1: &[u8; 64 * 64],
    pi1: usize,
    prgc_legal2: &[u8; 64],
    prgsq_piece2: &[u8; 64 * 64],
    pi2: usize,
    prgc_legal3: &[u8; 64],
    prgsq_piece3: &[u8; 64 * 64],
    pi3: usize,
    pc_enumeration: &mut u32,
) {
    let mut i_index: u32 = 0;
    for sq_king1 in 0u32..64 {
        for sq_king2 in 0u32..64 {
            let king_val = prgs_kings[(sq_king1 * 64 + sq_king2) as usize];
            if king_val != INF {
                let idx = king_val as usize;
                prg_index[idx] = i_index;
                let c1 = prgc_legal1[sq_king2 as usize] as u32
                    - (prgsq_piece1[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                        as u32;
                if pi1 == pi2 && pi2 == pi3 {
                    i_index += c1 * (c1 - 1) * (c1 - 2) / 6;
                } else if pi1 == pi2 {
                    let c3 = prgc_legal3[sq_king2 as usize] as u32
                        - (prgsq_piece3[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                            as u32;
                    i_index += c1 * (c1 - 1) / 2 * c3;
                } else if pi2 == pi3 {
                    let c2 = prgc_legal2[sq_king2 as usize] as u32
                        - (prgsq_piece2[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                            as u32;
                    i_index += c1 * c2 * (c2 - 1) / 2;
                } else {
                    let c2 = prgc_legal2[sq_king2 as usize] as u32
                        - (prgsq_piece2[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                            as u32;
                    let c3 = prgc_legal3[sq_king2 as usize] as u32
                        - (prgsq_piece3[(sq_king2 as usize) * 64 + (sq_king1 as usize)] != 0xFF)
                            as u32;
                    i_index += c1 * c2 * c3;
                }
            }
        }
    }
    *pc_enumeration = i_index;
}

