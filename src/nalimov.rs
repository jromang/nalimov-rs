// ── O(1) LRU cache (intrusive doubly-linked list + HashMap) ──────────────

const CACHE_BLOCKS_PER_MB: usize = 128; // 1 MiB / 8 KiB

fn cache_blocks_for_size_mb(cache_size_mb: usize) -> Result<usize, NalimovError> {
    cache_size_mb
        .checked_mul(CACHE_BLOCKS_PER_MB)
        .filter(|&blocks| blocks > 0)
        .ok_or(NalimovError::InvalidCacheSize)
}

struct LruEntry<K, V> {
    key: std::mem::MaybeUninit<K>,
    val: std::mem::MaybeUninit<V>,
    prev: *mut LruEntry<K, V>,
    next: *mut LruEntry<K, V>,
}

/// LRU cache with O(1) get/put via HashMap + intrusive doubly-linked list.
struct LruCache<K: Eq + std::hash::Hash + Copy, V> {
    map: HashMap<K, NonNull<LruEntry<K, V>>>,
    head: *mut LruEntry<K, V>, // sigil: head.next = most recent
    tail: *mut LruEntry<K, V>, // sigil: tail.prev = least recent
    cap: usize,
}

impl<K: Eq + std::hash::Hash + Copy, V> LruCache<K, V> {
    fn new(cap: usize) -> Self {
        let head = Box::into_raw(Box::new(LruEntry {
            key: std::mem::MaybeUninit::uninit(),
            val: std::mem::MaybeUninit::uninit(),
            prev: ptr::null_mut(),
            next: ptr::null_mut(),
        }));
        let tail = Box::into_raw(Box::new(LruEntry {
            key: std::mem::MaybeUninit::uninit(),
            val: std::mem::MaybeUninit::uninit(),
            prev: ptr::null_mut(),
            next: ptr::null_mut(),
        }));
        unsafe {
            (*head).next = tail;
            (*tail).prev = head;
        }
        LruCache {
            map: HashMap::with_capacity(cap),
            head,
            tail,
            cap,
        }
    }

    #[inline]
    fn detach(&self, node: *mut LruEntry<K, V>) {
        unsafe {
            (*(*node).prev).next = (*node).next;
            (*(*node).next).prev = (*node).prev;
        }
    }

    #[inline]
    fn attach(&self, node: *mut LruEntry<K, V>) {
        unsafe {
            (*node).next = (*self.head).next;
            (*node).prev = self.head;
            (*self.head).next = node;
            (*(*node).next).prev = node;
        }
    }

    fn get(&mut self, key: &K) -> Option<&V> {
        if let Some(&node) = self.map.get(key) {
            let node_ptr = node.as_ptr();
            self.detach(node_ptr);
            self.attach(node_ptr);
            Some(unsafe { &*(*node_ptr).val.as_ptr() })
        } else {
            None
        }
    }

    fn put(&mut self, key: K, val: V) {
        if let Some(&node) = self.map.get(&key) {
            let node_ptr = node.as_ptr();
            unsafe {
                // Drop old value, write new
                (*node_ptr).val.assume_init_drop();
                (*node_ptr).val = std::mem::MaybeUninit::new(val);
            }
            self.detach(node_ptr);
            self.attach(node_ptr);
        } else if self.map.len() >= self.cap {
            // Evict LRU entry (tail.prev) and reuse its node
            let old_ptr = unsafe { (*self.tail).prev };
            self.detach(old_ptr);
            let old_key = unsafe { (*old_ptr).key.assume_init() };
            self.map.remove(&old_key);
            unsafe {
                (*old_ptr).val.assume_init_drop();
                (*old_ptr).key = std::mem::MaybeUninit::new(key);
                (*old_ptr).val = std::mem::MaybeUninit::new(val);
            }
            self.attach(old_ptr);
            self.map.insert(key, unsafe { NonNull::new_unchecked(old_ptr) });
        } else {
            let node = Box::into_raw(Box::new(LruEntry {
                key: std::mem::MaybeUninit::new(key),
                val: std::mem::MaybeUninit::new(val),
                prev: ptr::null_mut(),
                next: ptr::null_mut(),
            }));
            self.attach(node);
            self.map.insert(key, unsafe { NonNull::new_unchecked(node) });
        }
    }
}

// SAFETY: LruCache owns all its nodes exclusively; the raw pointers never escape.
unsafe impl<K: Eq + std::hash::Hash + Copy + Send, V: Send> Send for LruCache<K, V> {}

impl<K: Eq + std::hash::Hash + Copy, V> Drop for LruCache<K, V> {
    fn drop(&mut self) {
        // Free all data entries (between head and tail sigils)
        let mut node = unsafe { (*self.head).next };
        while node != self.tail {
            let next = unsafe { (*node).next };
            unsafe {
                (*node).key.assume_init_drop();
                (*node).val.assume_init_drop();
                let _ = Box::from_raw(node);
            }
            node = next;
        }
        // Free sigils (no key/val to drop — they're uninit)
        let _ = unsafe { Box::from_raw(self.head) };
        let _ = unsafe { Box::from_raw(self.tail) };
    }
}

