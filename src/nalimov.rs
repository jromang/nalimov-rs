//!     uint64_t, uint64_t, uint64_t, uint64_t, int, uint8_t, int *);
//!
//! int main() {
//!     rs_nalimov_init("/path/to/nalimov/3-4-5");
//!
//!     // KRvK: White Ke1(4) Rh1(7), Black Ka8(56)
//!     uint64_t white = (1ULL << 4) | (1ULL << 7);
//!     uint64_t black = (1ULL << 56);
//!     uint64_t kings = (1ULL << 4) | (1ULL << 56);
//!     uint64_t rooks = (1ULL << 7);
//!     int score;
//!
//!     if (rs_nalimov_probe(white, black, kings, 0, rooks, 0, 0, 0, 1, 64, &score))
//!         printf("Score: %d\n", score);  // positive = White wins
//!     return 0;
//! }
//! ```
//!
//! # Probe parameters
//!
//! All bitboards use Little-Endian Rank-File mapping: `a1=0, b1=1, …, h8=63`.
//! Each piece-type bitboard (`kings`, `queens`, …) contains bits for **both colors**.
//! The `white` / `black` bitboards disambiguate ownership.
//!
//! | Parameter   | Type   | Description |
//! |-------------|--------|-------------|
//! | `white`     | `u64`  | All white pieces |
//! | `black`     | `u64`  | All black pieces |
//! | `kings`     | `u64`  | Both kings |
//! | `queens`    | `u64`  | Both queens |
//! | `rooks`     | `u64`  | Both rooks |
//! | `bishops`   | `u64`  | Both bishops |
//! | `knights`   | `u64`  | Both knights |
//! | `pawns`     | `u64`  | Both pawns |
//! | `wtm`       | `bool` | `true` = White to move |
//! | `ep_square` | `u8`   | EP target square (0–63), or 64 if none |
//!
//! Returns `Win { plies }`, `Loss { plies }`, or `Draw` from the **side to move's** perspective.
//!
//! # Implementation outline
//!
//! - **S1** — Public types, piece constants, `s_to_l` score conversion
//! - **S2** — Static lookup tables (`rgsTriKings`, `rgsHalfKings`, reflection masks)
//! - **S3** — Enumeration tables (lazy-initialized via `OnceLock`)
//! - **S4** — Index calculation (`TEnumerate1/2/3`, `T21–T42/T33` dispatch)
//! - **S5** — LZ77+Huffman decompressor (port of `tbdecode.h`)
//! - **S6** — `NalimovProber`: file discovery, probe flow, LRU cache
//! - **S7** — C API: `rs_nalimov_init`, `rs_nalimov_probe`

