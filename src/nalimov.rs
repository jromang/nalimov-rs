const HEADER_SIZE: usize = 80;
const MAX_BLOCK_BITS: usize = 16;
const MAX_BITS_HALF: usize = (MAX_BLOCK_BITS + 1) >> 1;
const MAX_BITS: usize = MAX_BITS_HALF * 2;
const MAX_LENGTH_BITS: usize = 5;
const MAX_LENGTH: usize = 1 << MAX_LENGTH_BITS; // 32
const LONG_BITS: usize = 1;
const LONG_LENGTH: usize = MAX_BLOCK_BITS - LONG_BITS; // 15
const LONG_QUICK: usize = MAX_LENGTH - LONG_LENGTH; // 17
const DELTA: usize = LONG_BITS + LONG_QUICK - 1; // 17
const MAX_DISTANCES: usize = 24;
const ALPHABET_SIZE: usize = 256 + (MAX_DISTANCES << MAX_LENGTH_BITS); // 1024
const START_BITS: usize = 13;
const SHORT_INDEX: u32 = 8;
const MIN_REPT: usize = 2;
const TEMP_TABLE_BITS: usize = 8;

static HEADER_TITLE: &[u8; 64] =
    b"Compressed by DATACOMP v 1.0 (c) 1991--1998 Andrew Kadatch\r\n\0\0\0\0";

fn huffman_table_size(n: usize, start_bits: usize) -> usize {
    (1 << start_bits) + (n << 1)
}

// CRC32 with Nalimov's inverted polynomial (XOR when bit is 0)
fn crc32_init_table() -> [u32; 256] {
    let mut table = [0u32; 256];
    let m: u32 = 0xedb88320;
    for i in 0..256 {
        let mut k = i as u32;
        for _ in 0..8 {
            if (k & 1) != 0 {
                k >>= 1;
            } else {
                k >>= 1;
                k ^= m;
            }
        }
        table[i] = k;
    }
    table
}

fn crc32_compute(data: &[u8], init: u32) -> u32 {
    static TABLE: OnceLock<[u32; 256]> = OnceLock::new();
    let table = TABLE.get_or_init(crc32_init_table);
    let mut k = init;
    // Process 16 bytes at a time (matches C++ unrolled loop)
    let mut chunks = data.chunks_exact(16);
    for chunk in &mut chunks {
        k = table[((k as u8) ^ chunk[0]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[1]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[2]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[3]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[4]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[5]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[6]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[7]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[8]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[9]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[10]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[11]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[12]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[13]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[14]) as usize] ^ (k >> 8);
        k = table[((k as u8) ^ chunk[15]) as usize] ^ (k >> 8);
    }
    for &b in chunks.remainder() {
        k = table[((k as u8) ^ b) as usize] ^ (k >> 8);
    }
    k
}

/// Bit reader (equivalent to bitio_t)
struct BitReader<'a> {
    mask: u32,
    bits: i32,
    ptr: &'a [u8],
    pos: usize,
}

impl<'a> BitReader<'a> {
    fn new(data: &'a [u8], offset: usize) -> Self {
        let mut br = BitReader {
            mask: 0,
            bits: 0,
            ptr: data,
            pos: offset,
        };
        // BIORD_START: read up to 4 bytes big-endian
        br.mask = 0;
        let avail = br.ptr.len() - br.pos;
        let n = avail.min(4);
        for _ in 0..n {
            br.mask = (br.mask << 8) | (br.ptr[br.pos] as u32);
            br.pos += 1;
        }
        // Left-align if we read fewer than 4 bytes
        br.mask <<= (4 - n) * 8;
        br.bits = 16;
        br
    }

    /// Read top `bits` bits without consuming.
    #[inline]
    fn peek(&self, bits: usize) -> u32 {
        self.mask >> (32 - bits)
    }

    /// Consume `bits` bits and refill from stream.
    #[inline(always)]
    fn advance(&mut self, bits: usize) {
        self.mask <<= bits;
        self.bits -= bits as i32;
        if self.bits <= 0 {
            // Refill 16 bits. Read 2 bytes big-endian if available.
            let remaining = self.ptr.len() - self.pos;
            if remaining >= 2 {
                let refill = ((self.ptr[self.pos] as u32) << 8) | (self.ptr[self.pos + 1] as u32);
                self.mask |= refill << ((-self.bits) as u32);
                self.pos += 2;
            } else if remaining >= 1 {
                self.mask |= ((self.ptr[self.pos] as u32) << 8) << ((-self.bits) as u32);
                self.pos += 1;
            }
            self.bits += 16;
        }
    }

    /// Peek + advance combined.
    #[inline(always)]
    fn read(&mut self, bits: usize) -> u32 {
        let v = self.mask >> (32 - bits);
        self.advance(bits);
        v
    }
}

/// Huffman decode from table.
#[inline(always)]
fn huffman_decode(br: &mut BitReader, table: &[i32], start_bits: usize) -> i32 {
    let mut ch = table[br.peek(start_bits) as usize];
    if ch >= 0 {
        // Fast path: symbol decoded from direct lookup
        br.advance((ch & 31) as usize);
        return ch >> 5;
    }
    // Slow path: walk the tree bit by bit
    br.advance(start_bits);
    loop {
        ch = table[(br.peek(1) as i32 - ch) as usize];
        br.advance(1);
        if ch >= 0 {
            return ch;
        }
    }
}

/// Create Huffman decode table. Returns Ok(()) or error.
fn huffman_decode_create(
    table: &mut [i32],
    length: &[u8],
    n: usize,
    start_bits: usize,
) -> Result<(), String> {
    let mut freq = [0i32; 32];
    let mut sum = [0i32; 32];

    for i in 0..n {
        let k = length[i] as usize;
        if k > 31 {
            return Err("huffman length > 31".into());
        }
        freq[k] += 1;
    }

    if freq[0] == n as i32 {
        for i in 0..(1 << start_bits) {
            table[i] = 0;
        }
        return Ok(());
    }
    if freq[0] == (n as i32 - 1) {
        if freq[1] != 1 {
            return Err("huffman broken (single symbol)".into());
        }
        let mut sym = 0;
        for i in 0..n {
            if length[i] != 0 {
                sym = i;
                break;
            }
        }
        let val = (sym as i32) << 5;
        for i in 0..(1 << start_bits) {
            table[i] = val;
        }
        return Ok(());
    }

    sum.copy_from_slice(&freq);

    // Check code correctness
    let mut k = 0i32;
    for i in (1..32).rev() {
        k += freq[i];
        if (k & 1) != 0 {
            return Err("huffman code not canonical".into());
        }
        k >>= 1;
    }
    if k != 1 {
        return Err("huffman code invalid".into());
    }

    // Sort symbols
    k = 0;
    for i in 1..32 {
        freq[i] = {
            k += freq[i];
            k
        };
    }
    let last = freq[31] as usize;
    for i in (0..n).rev() {
        let kk = length[i] as usize;
        if kk != 0 {
            freq[kk] -= 1;
            table[freq[kk] as usize] = i as i32;
        }
    }

    // Create decoding table
    let table_total = (1 << start_bits) + (n << 1);
    let mut kk = table_total as i32;
    let mut i = table_total as i32;
    let mut last_pos = last;
    for nn in (start_bits + 1..32).rev() {
        let j = i;
        while kk > j {
            i -= 1;
            kk -= 2;
            table[i as usize] = -kk;
        }
        let mut s = sum[nn];
        while s > 0 {
            s -= 1;
            last_pos -= 1;
            i -= 1;
            table[i as usize] = table[last_pos];
        }
        kk = j;
    }

    let j = i;
    i = 1 << start_bits;
    while kk > j {
        i -= 1;
        kk -= 2;
        table[i as usize] = -kk;
    }

    for nn in (1..=start_bits).rev() {
        let mut s = sum[nn];
        while s > 0 {
            s -= 1;
            assert!(last_pos <= i as usize && last_pos > 0);
            last_pos -= 1;
            let sym_val = table[last_pos];
            let step = 1usize << (start_bits - nn);
            let mut jj = i as usize;
            let target = jj - step;
            let encoded = nn as i32 | (sym_val << 5);
            while jj > target {
                jj -= 1;
                table[jj] = encoded;
            }
            i = target as i32;
        }
    }

    Ok(())
}

/// Read Huffman code lengths (recursive).
fn huffman_read_length(br: &mut BitReader, length: &mut [u8], n: usize) -> Result<(), String> {
    let k = br.read(1);
    if k != 0 {
        length[..n].fill(0);
        return Ok(());
    }

    if n <= 128 {
        let bits = br.read(5) as usize;
        let mut i = 0;
        while i < n {
            length[i] = br.read(bits) as u8;
            i += 1;
            if length[i - 1] == 0 {
                let j = i + br.read(4) as usize;
                if j > n {
                    return Err("huffman length overflow".into());
                }
                while i < j {
                    length[i] = 0;
                    i += 1;
                }
            }
        }
        return Ok(());
    }

    let mut bits = [0u8; 128];
    huffman_read_length(br, &mut bits, 128)?;

    let tbl_size = huffman_table_size(64, TEMP_TABLE_BITS);
    let mut table0 = vec![0i32; tbl_size];
    let mut table1 = vec![0i32; tbl_size];
    huffman_decode_create(&mut table0, &bits[..64], 64, TEMP_TABLE_BITS)?;
    huffman_decode_create(&mut table1, &bits[64..128], 64, TEMP_TABLE_BITS)?;

    let mut i = 0;
    while i < n {
        let mut k = huffman_decode(br, &table0, TEMP_TABLE_BITS);
        if k <= 31 {
            length[i] = k as u8;
            i += 1;
            continue;
        }
        k &= 31;
        let mut j = huffman_decode(br, &table1, TEMP_TABLE_BITS);
        if j > 31 {
            let jj = (j - 32) as usize;
            j = 1 << jj;
            if jj != 0 {
                if jj > 16 {
                    j += (br.read(16) << (jj - 16)) as i32;
                }
                j += br.read(jj) as i32;
            }
            j += 31;
        }
        j += MIN_REPT as i32 + i as i32;
        if j as usize > n {
            return Err("huffman rept overflow".into());
        }
        while (i as i32) < j {
            length[i] = k as u8;
            i += 1;
        }
    }

    Ok(())
}

/// Decoded compression info (per-file).
struct DecodeInfo {
    table: Vec<i32>,
    distance: [i32; MAX_DISTANCES],
    crc: Vec<u32>,
    blk_u: Vec<u32>,
    blk_s: Vec<u16>,
    block_size: usize,
    last_block_size: usize,
    n_blk: usize,
    check_crc: bool,
}

fn calculate_offset(info: &DecodeInfo, n: u32) -> u32 {
    let i = n / (2 * SHORT_INDEX);
    if (n & SHORT_INDEX) != 0 {
        info.blk_u[(i + 1) as usize] - info.blk_s[n as usize] as u32
    } else {
        info.blk_u[i as usize] + info.blk_s[n as usize] as u32
    }
}

/// Parse compression header from in-memory file data.
fn comp_open(data: &[u8], check_crc: bool) -> Result<DecodeInfo, String> {
    if data.len() < HEADER_SIZE {
        return Err("file too small".into());
    }

    // Verify header title
    if &data[..64] != &HEADER_TITLE[..] {
        return Err("invalid header title".into());
    }

    let r4 = |offset: usize| -> u32 {
        ((data[offset] as u32) << 24)
            | ((data[offset + 1] as u32) << 16)
            | ((data[offset + 2] as u32) << 8)
            | (data[offset + 3] as u32)
    };

    let header_size = r4(64) as usize;
    let block_size_log = data[70] as usize;
    if block_size_log > MAX_BITS || header_size < 84 {
        return Err("invalid block size log".into());
    }
    let block_size = 1 << block_size_log;
    if data[71] as usize != MAX_DISTANCES {
        return Err("invalid max distances".into());
    }
    let n_blk = r4(72) as usize;
    let expected = (ALPHABET_SIZE << 12) | (LONG_BITS << 8) | (LONG_LENGTH << 4) | MAX_LENGTH_BITS;
    if r4(76) as usize != expected {
        return Err("invalid compression parameters".into());
    }

    if data.len() < header_size {
        return Err("file truncated at header".into());
    }

    // CRC check on header
    let hdr_crc_offset = header_size - 4;
    let computed_crc = crc32_compute(&data[..hdr_crc_offset], 0);
    let stored_crc = r4(hdr_crc_offset);
    if computed_crc != stored_crc {
        return Err("header CRC mismatch".into());
    }

    // Read per-block CRCs
    let mut crc_data = Vec::new();
    if check_crc {
        let crc_count = n_blk * 2;
        let mut offset = HEADER_SIZE;
        for _ in 0..crc_count {
            crc_data.push(r4(offset));
            offset += 4;
        }
    }

    // Read block sizes
    let bsl_offset = HEADER_SIZE + (n_blk << 3);
    let mut br = BitReader::new(data, bsl_offset);

    let mut blk = vec![0u32; n_blk + 1];
    for i in 0..=n_blk {
        let mut v = br.read(block_size_log);
        if v == 0 {
            v = block_size as u32;
        }
        blk[i] = v;
    }

    // Read distances
    let mut distance = [0i32; MAX_DISTANCES];
    for i in 0..MAX_DISTANCES {
        distance[i] = -(br.read(block_size_log) as i32);
    }

    // Read Huffman table
    let huff_bit_offset =
        bsl_offset + (((n_blk + 1 + MAX_DISTANCES) * block_size_log + 7) >> 3);
    let mut br2 = BitReader::new(data, huff_bit_offset);
    let mut temp = [0u8; ALPHABET_SIZE];
    huffman_read_length(&mut br2, &mut temp, ALPHABET_SIZE)?;

    let tbl_size = huffman_table_size(ALPHABET_SIZE, START_BITS);
    let mut table = vec![0i32; tbl_size];
    huffman_decode_create(&mut table, &temp, ALPHABET_SIZE, START_BITS)?;

    let last_block_size = blk[n_blk] as usize;
    blk[n_blk] = 0;

    let mut hdr_size_running = header_size as u32;
    for i in 0..=n_blk {
        let sz = blk[i];
        blk[i] = hdr_size_running;
        hdr_size_running += sz;
    }

    // Build short index
    let n_u = 2 + n_blk / (2 * SHORT_INDEX as usize);
    let mut blk_u = vec![0u32; n_u];
    let mut blk_s = vec![0u16; n_blk + 1];

    for i in 0..=n_blk {
        if (i as u32) % (2 * SHORT_INDEX) == 0 {
            blk_u[i / (2 * SHORT_INDEX as usize)] = blk[i];
        }
    }
    blk_u[n_blk / (2 * SHORT_INDEX as usize) + 1] = blk[n_blk];

    for i in 0..=n_blk {
        let bucket = i / (2 * SHORT_INDEX as usize);
        if ((i as u32) & SHORT_INDEX) != 0 {
            blk_s[i] = (blk_u[bucket + 1] - blk[i]) as u16;
        } else {
            blk_s[i] = (blk[i] - blk_u[bucket]) as u16;
        }
    }

    Ok(DecodeInfo {
        table,
        distance,
        crc: crc_data,
        blk_u,
        blk_s,
        block_size,
        last_block_size,
        n_blk,
        check_crc,
    })
}

/// Parse compression header by reading only the header portion of a file.
fn comp_open_from_file(path: &str) -> Result<DecodeInfo, String> {
    let mut f = File::open(path).map_err(|e| format!("{path}: {e}"))?;

    // Read the fixed header (80 bytes) to learn the full header size.
    let mut fixed = [0u8; HEADER_SIZE];
    f.read_exact(&mut fixed).map_err(|e| format!("{path}: read header: {e}"))?;

    if &fixed[..64] != &HEADER_TITLE[..] {
        return Err(format!("{path}: invalid header title"));
    }

    let header_size = u32::from_be_bytes([fixed[64], fixed[65], fixed[66], fixed[67]]) as usize;
    if header_size < 84 {
        return Err(format!("{path}: invalid header size {header_size}"));
    }
    let n_blk = u32::from_be_bytes([fixed[72], fixed[73], fixed[74], fixed[75]]) as usize;

    // Now read the full header (all metadata including CRCs, block sizes, huffman table).
    // The compressed block data starts at offset `header_size`, so we need all bytes before that.
    // The block-size table and huffman data may extend slightly beyond `header_size` (the offset
    // table is packed in bits), so read a generous amount.
    let meta_size = header_size + (n_blk + 1 + MAX_DISTANCES + 1) * 2 + 4096;
    let file_len = f.seek(SeekFrom::End(0)).map_err(|e| format!("{path}: seek end: {e}"))? as usize;
    let read_size = meta_size.min(file_len);
    let mut buf = vec![0u8; read_size];
    f.seek(SeekFrom::Start(0)).map_err(|e| format!("{path}: seek start: {e}"))?;
    f.read_exact(&mut buf).map_err(|e| format!("{path}: read meta: {e}"))?;

    comp_open(&buf, false)
}

/// Read and decompress a single block from a file on disk (no full-file loading).
fn decompress_block_from_file(
    info: &DecodeInfo,
    path: &str,
    block_num: usize,
) -> Result<Vec<u8>, String> {
    if block_num >= info.n_blk {
        return Err("block number out of range".into());
    }

    let comp_start = calculate_offset(info, block_num as u32) as u64;
    let comp_end = calculate_offset(info, (block_num + 1) as u32) as u64;
    let comp_size = (comp_end - comp_start) as usize;
    let orig_size = if block_num == info.n_blk - 1 {
        info.last_block_size
    } else {
        info.block_size
    };

    // Read just the compressed bytes from disk
    let mut f = File::open(path).map_err(|e| format!("{path}: {e}"))?;
    f.seek(SeekFrom::Start(comp_start)).map_err(|e| format!("{path}: seek: {e}"))?;
    let mut comp_data = vec![0u8; comp_size];
    f.read_exact(&mut comp_data).map_err(|e| format!("{path}: read block: {e}"))?;

    // CRC check on compressed data
    if info.check_crc && !info.crc.is_empty() {
        let expected = info.crc[block_num * 2 + 1];
        let computed = crc32_compute(&comp_data, 0);
        if expected != computed {
            return Err("compressed block CRC mismatch".into());
        }
    }

    if comp_size == orig_size {
        return Ok(comp_data);
    }

    // Decompress using LZ77+Huffman
    decompress_raw(info, &comp_data, orig_size, block_num)
}

/// Core LZ77+Huffman decompression from compressed bytes.
fn decompress_raw(
    info: &DecodeInfo,
    comp_data: &[u8],
    orig_size: usize,
    block_num: usize,
) -> Result<Vec<u8>, String> {
    let mut output = vec![0u8; orig_size];
    let mut br = BitReader::new(comp_data, 0);
    let mut p = 0usize;

    while p < orig_size {
        let mut ch = huffman_decode(&mut br, &info.table, START_BITS);
        ch -= 256;
        if ch < 0 {
            output[p] = ch as u8;
            p += 1;
            continue;
        }

        let dist = info.distance[(ch >> MAX_LENGTH_BITS) as usize];
        let s = (p as i32 + dist) as usize;

        let mut len = ch & ((MAX_LENGTH - 1) as i32);
        if len >= LONG_LENGTH as i32 {
            len -= LONG_LENGTH as i32 - LONG_BITS as i32;
            if len == DELTA as i32 {
                len = br.read(5) as i32 + DELTA as i32;
            }
            let mut n = 1i32 << len;
            if len > 16 {
                n += (br.read(16) << (len - 16)) as i32;
            }
            n += br.read(len as usize) as i32;
            len = n + LONG_LENGTH as i32 - (1 << LONG_BITS);
        }
        let len = (len + 1) as usize;

        if s + len <= p {
            output.copy_within(s..s + len, p);
        } else {
            for i in 0..len {
                output[p + i] = output[s + i];
            }
        }
        p += len;
    }

    // CRC check on decompressed data
    if info.check_crc && !info.crc.is_empty() {
        let expected = info.crc[block_num * 2];
        let computed = crc32_compute(&output, 0);
        if expected != computed {
            return Err("decompressed block CRC mismatch".into());
        }
    }

    Ok(output)
}

