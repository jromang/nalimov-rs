/// Result of a Nalimov tablebase probe.
///
/// Scores are from the perspective of the **side to move**:
/// - `Win` = the side to move wins with best play
/// - `Loss` = the side to move loses with best play
/// - `Draw` = the position is drawn
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NalimovResult {
    Win { plies: u16 },
    Loss { plies: u16 },
    Draw,
}

/// Errors that can occur during probing.
#[derive(Debug)]
pub enum NalimovError {
    Io(std::io::Error),
    InvalidCacheSize,
    NoTablebases,
    PositionNotFound,
    DecompressError(String),
}

impl From<std::io::Error> for NalimovError {
    fn from(e: std::io::Error) -> Self {
        NalimovError::Io(e)
    }
}

