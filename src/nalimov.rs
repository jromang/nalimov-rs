/// Lazily initialized enumeration tables for Nalimov index calculation.
struct Enumerations {
    // sq_piece[piece][king_sq*64 + piece_sq] -> enumerated index (0xFF = illegal)
    sq_piece: [[u8; 64 * 64]; 6],
    // c_legal[piece][king_sq] -> count of legal squares
    c_legal: [[u8; 64]; 6],
    // Single piece offset tables
    single_pawnless: [[u32; 462]; 6],
    single_pawn: [[u32; 1806]; 6],
    // Pair piece offset tables
    pair_pawnless: [[[u32; 462]; 6]; 6],
    pair_pawn: [[[u32; 1806]; 6]; 6],
    // Triple piece offset tables (boxed because very large)
    triple_pawnless: Box<[[[[u32; 462]; 6]; 6]; 6]>,
    triple_pawn: Box<[[[[u32; 1806]; 6]; 6]; 6]>,
    // Total enumeration counts
    count_single_pawnless: [u32; 6],
    count_single_pawn: [u32; 6],
    count_pair_pawnless: [[u32; 6]; 6],
    count_pair_pawn: [[u32; 6]; 6],
    count_triple_pawnless: [[[u32; 6]; 6]; 6],
    count_triple_pawn: [[[u32; 6]; 6]; 6],
}

fn get_enumerations() -> &'static Enumerations {
    static ENUMS: OnceLock<Box<Enumerations>> = OnceLock::new();
    ENUMS.get_or_init(|| {
        let mut e = Box::new(Enumerations {
            sq_piece: [[0xFF; 64 * 64]; 6],
            c_legal: [[0; 64]; 6],
            single_pawnless: [[0; 462]; 6],
            single_pawn: [[0; 1806]; 6],
            pair_pawnless: [[[0; 462]; 6]; 6],
            pair_pawn: [[[0; 1806]; 6]; 6],
            triple_pawnless: Box::new([[[[0; 462]; 6]; 6]; 6]),
            triple_pawn: Box::new([[[[0; 1806]; 6]; 6]; 6]),
            count_single_pawnless: [0; 6],
            count_single_pawn: [0; 6],
            count_pair_pawnless: [[0; 6]; 6],
            count_pair_pawn: [[0; 6]; 6],
            count_triple_pawnless: [[[0; 6]; 6]; 6],
            count_triple_pawn: [[[0; 6]; 6]; 6],
        });

        let tri_kings = get_tri_kings();
        let half_kings = get_half_kings();

        // Initialize square tables for each piece type
        for pi in 0..=X_PIECE_QUEEN {
            v_init_squares_table(pi, &mut e.sq_piece[pi], &mut e.c_legal[pi]);
        }

        // Initialize single/pair/triple enumeration tables
        for pi1 in 0..=X_PIECE_QUEEN {
            // Single pawn-present
            v_init_single(
                &mut e.single_pawn[pi1],
                half_kings,
                &e.c_legal[pi1],
                &e.sq_piece[pi1],
                &mut e.count_single_pawn[pi1],
            );
            // Single pawnless (only for pi > pawn)
            if pi1 > X_PIECE_PAWN {
                v_init_single(
                    &mut e.single_pawnless[pi1],
                    tri_kings,
                    &e.c_legal[pi1],
                    &e.sq_piece[pi1],
                    &mut e.count_single_pawnless[pi1],
                );
            }

            // Pairs
            let pi2_start = if pi1 == X_PIECE_NONE {
                X_PIECE_NONE
            } else {
                X_PIECE_PAWN
            };
            for pi2 in pi2_start..=pi1 {
                // Pair pawn-present
                v_init_pair(
                    &mut e.pair_pawn[pi1][pi2],
                    half_kings,
                    &e.c_legal[pi1],
                    &e.sq_piece[pi1],
                    pi1,
                    &e.c_legal[pi2],
                    &e.sq_piece[pi2],
                    pi2,
                    &mut e.count_pair_pawn[pi1][pi2],
                );
                if pi1 > X_PIECE_PAWN && pi2 > X_PIECE_PAWN {
                    // Pair pawnless
                    v_init_pair(
                        &mut e.pair_pawnless[pi1][pi2],
                        tri_kings,
                        &e.c_legal[pi1],
                        &e.sq_piece[pi1],
                        pi1,
                        &e.c_legal[pi2],
                        &e.sq_piece[pi2],
                        pi2,
                        &mut e.count_pair_pawnless[pi1][pi2],
                    );
                }

                // Triples
                let pi3_start = if pi1 == X_PIECE_NONE {
                    X_PIECE_NONE
                } else {
                    X_PIECE_PAWN
                };
                for pi3 in pi3_start..=pi2 {
                    if pi1 <= X_PIECE_PAWN || pi2 <= X_PIECE_PAWN || pi3 <= X_PIECE_PAWN {
                        // pawn-present triple
                        v_init_triple(
                            &mut e.triple_pawn[pi1][pi2][pi3],
                            half_kings,
                            &e.c_legal[pi1],
                            &e.sq_piece[pi1],
                            pi1,
                            &e.c_legal[pi2],
                            &e.sq_piece[pi2],
                            pi2,
                            &e.c_legal[pi3],
                            &e.sq_piece[pi3],
                            pi3,
                            &mut e.count_triple_pawn[pi1][pi2][pi3],
                        );
                    } else {
                        // pawnless triple
                        v_init_triple(
                            &mut e.triple_pawnless[pi1][pi2][pi3],
                            tri_kings,
                            &e.c_legal[pi1],
                            &e.sq_piece[pi1],
                            pi1,
                            &e.c_legal[pi2],
                            &e.sq_piece[pi2],
                            pi2,
                            &e.c_legal[pi3],
                            &e.sq_piece[pi3],
                            pi3,
                            &mut e.count_triple_pawnless[pi1][pi2][pi3],
                        );
                        // Also build pawn-present version for T42 BTM
                        v_init_triple(
                            &mut e.triple_pawn[pi1][pi2][pi3],
                            half_kings,
                            &e.c_legal[pi1],
                            &e.sq_piece[pi1],
                            pi1,
                            &e.c_legal[pi2],
                            &e.sq_piece[pi2],
                            pi2,
                            &e.c_legal[pi3],
                            &e.sq_piece[pi3],
                            pi3,
                            &mut e.count_triple_pawn[pi1][pi2][pi3],
                        );
                    }
                }
            }
        }

        e
    })
}

