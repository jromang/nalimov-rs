/// Main prober for Nalimov endgame tablebases.
pub struct NalimovProber {
    state: Mutex<NalimovState>,
}

struct NalimovState {
    /// tables[config_hash] -> [extents_for_wtm, extents_for_btm]
    /// Each side maps extent_index -> TbFile.
    /// Non-split tables have a single entry at extent 0.
    tables: HashMap<u32, [BTreeMap<usize, TbFile>; 2]>,
    /// LRU cache of decompressed 8KB blocks.
    /// Key: (config_hash, side, extent_index, block_num_within_extent)
    cache: LruCache<(u32, u8, usize, usize), Vec<u8>>,
}

/// djb2 hash for configuration strings.
fn djb2_hash(s: &str) -> u32 {
    let mut hash: u32 = 5381;
    for b in s.bytes() {
        hash = hash.wrapping_mul(33).wrapping_add(b as u32);
    }
    hash
}

/// Build canonical config hash and inversion flag from piece counters.
/// Zero-allocation: works entirely on the stack.
/// rgi_counters: [0-4] = white P,N,B,R,Q counts; [5-9] = black P,N,B,R,Q counts
fn build_config_hash(rgi_counters: &[u32; 10]) -> (u32, bool) {
    let w_total: u32 = rgi_counters[0..5].iter().sum();
    let b_total: u32 = rgi_counters[5..10].iter().sum();

    let w_strength: u32 = rgi_counters[0..5]
        .iter()
        .enumerate()
        .map(|(i, &c)| c * (i as u32 + 1))
        .sum();
    let b_strength: u32 = rgi_counters[5..10]
        .iter()
        .enumerate()
        .map(|(i, &c)| c * (i as u32 + 1))
        .sum();

    let invert = if w_total != b_total {
        b_total > w_total
    } else {
        b_strength > w_strength
    };

    // Build config string on stack (max 8 chars: "k" + 3 pieces + "k" + 3 pieces)
    let mut buf = [0u8; 16];
    let mut pos = 0;

    let (first, second) = if invert { (5, 0) } else { (0, 5) };

    buf[pos] = b'k'; pos += 1;
    // Nalimov convention: pieces ordered by value descending (Q,R,B,N,P)
    let order = [4usize, 3, 2, 1, 0];
    let piece_chars = [b'p', b'n', b'b', b'r', b'q'];
    for &i in &order {
        for _ in 0..rgi_counters[first + i] {
            buf[pos] = piece_chars[i]; pos += 1;
        }
    }
    buf[pos] = b'k'; pos += 1;
    for &i in &order {
        for _ in 0..rgi_counters[second + i] {
            buf[pos] = piece_chars[i]; pos += 1;
        }
    }

    // djb2 hash inline
    let mut hash = 5381u32;
    for &b in &buf[..pos] {
        hash = hash.wrapping_mul(33).wrapping_add(b as u32);
    }

    (hash, invert)
}

/// Build config string (allocating version, used only for file discovery).
#[cfg(test)]
fn build_config(rgi_counters: &[u32; 10]) -> (String, bool) {
    let (_, invert) = build_config_hash(rgi_counters);

    let (first, second) = if invert { (5, 0) } else { (0, 5) };
    let mut config = String::with_capacity(10);
    let order = [4usize, 3, 2, 1, 0];
    let piece_chars = ['p', 'n', 'b', 'r', 'q'];

    config.push('k');
    for &i in &order {
        for _ in 0..rgi_counters[first + i] {
            config.push(piece_chars[i]);
        }
    }
    config.push('k');
    for &i in &order {
        for _ in 0..rgi_counters[second + i] {
            config.push(piece_chars[i]);
        }
    }

    (config, invert)
}

impl NalimovProber {
    /// Create a new prober by scanning directories for `.nbw.emd` / `.nbb.emd` files.
    ///
    /// Each path should be a directory containing Nalimov tablebase files.
    /// Files are memory-mapped at probe time (not at construction).
    /// Returns `Err(NoTablebases)` if no valid files are found.
    ///
    /// ```no_run
    /// use nalimov::NalimovProber;
    /// let prober = NalimovProber::new(
    ///     &["/path/to/3-4-5", "/path/to/6-piece"],
    ///     256,
    /// ).unwrap();
    /// ```
    pub fn new(paths: &[&str], cache_size_mb: usize) -> Result<Self, NalimovError> {
        let cache_blocks = cache_blocks_for_size_mb(cache_size_mb)?;

        // Force initialization of enumerations
        let _ = get_enumerations();

        let mut state = NalimovState {
            tables: HashMap::new(),
            cache: LruCache::new(cache_blocks),
        };

        let mut found_any = false;

        for path_str in paths {
            let path = Path::new(path_str);
            if !path.is_dir() {
                continue;
            }
            let entries = std::fs::read_dir(path)?;
            for entry in entries {
                let entry = entry?;
                let fname = entry.file_name().to_string_lossy().to_string();
                if !fname.ends_with(".emd") {
                    continue;
                }
                // Parse filename: "kqkr.nbw.emd" or "kbbkbp.0.nbw.emd" (extent)
                let base = fname.trim_end_matches(".emd");
                let (remaining, side_idx) = if base.ends_with(".nbw") {
                    (base.trim_end_matches(".nbw"), 0usize)
                } else if base.ends_with(".nbb") {
                    (base.trim_end_matches(".nbb"), 1usize)
                } else {
                    continue;
                };

                // Parse extent index: "kbbkbp.0" → config="kbbkbp", extent=0
                let (config, extent_idx) = match remaining.rfind('.') {
                    Some(dot) => match remaining[dot + 1..].parse::<usize>() {
                        Ok(idx) => (&remaining[..dot], idx),
                        Err(_) => (remaining, 0),
                    },
                    None => (remaining, 0),
                };

                let full_path = entry.path().to_string_lossy().to_string();
                let hash = djb2_hash(config);
                let is_16bit = config_is_16bit(config);

                // Store path only — decode_info loaded lazily on first probe
                let tb_file = TbFile {
                    path: full_path,
                    decode_info: None,
                    is_16bit,
                };

                let entry = state
                    .tables
                    .entry(hash)
                    .or_insert([BTreeMap::new(), BTreeMap::new()]);
                entry[side_idx].insert(extent_idx, tb_file);
                found_any = true;
            }
        }

        if !found_any {
            return Err(NalimovError::NoTablebases);
        }

        Ok(NalimovProber {
            state: Mutex::new(state),
        })
    }

    /// Probe Nalimov tablebases for an exact DTM (distance-to-mate) result.
    ///
    /// All bitboard parameters use Little-Endian Rank-File mapping:
    /// `a1=0, b1=1, …, h1=7, a2=8, …, h8=63`.
    ///
    /// Piece-type bitboards (`kings`, `queens`, …) contain squares for **both colors**.
    /// The `white` and `black` bitboards disambiguate ownership.
    ///
    /// Returns `Err(PositionNotFound)` for illegal positions or missing table files.
    pub fn probe(
        &self,
        white: u64,
        black: u64,
        kings: u64,
        queens: u64,
        rooks: u64,
        bishops: u64,
        knights: u64,
        pawns: u64,
        wtm: bool,
        ep_square: u8,
    ) -> Result<NalimovResult, NalimovError> {
        // Extract piece squares from bitboards using trailing_zeros (iterate only set bits)
        let mut rgi_counters = [0u32; 10];
        let mut rgsq_white = [0u32; C_PIECES * 5 + 1];
        let mut rgsq_black = [0u32; C_PIECES * 5 + 1];

        // Kings first (exactly 1 per side)
        rgsq_white[5 * C_PIECES] = (kings & white).trailing_zeros();
        rgsq_black[5 * C_PIECES] = (kings & black).trailing_zeros();

        // Non-king pieces: iterate set bits via trailing_zeros + clear LSB
        // Process each piece type × color pair directly
        macro_rules! extract_pieces {
            ($bb:expr, $pi_idx:expr, $counter_idx:expr, $rgsq:ident) => {
                let mut bits = $bb;
                while bits != 0 {
                    let sq = bits.trailing_zeros();
                    bits &= bits - 1;
                    let count = rgi_counters[$counter_idx] as usize;
                    $rgsq[$pi_idx * C_PIECES + count] = sq;
                    rgi_counters[$counter_idx] += 1;
                }
            };
        }
        extract_pieces!(queens & white,  4, 4, rgsq_white);
        extract_pieces!(queens & black,  4, 9, rgsq_black);
        extract_pieces!(rooks & white,   3, 3, rgsq_white);
        extract_pieces!(rooks & black,   3, 8, rgsq_black);
        extract_pieces!(bishops & white, 2, 2, rgsq_white);
        extract_pieces!(bishops & black, 2, 7, rgsq_black);
        extract_pieces!(knights & white, 1, 1, rgsq_white);
        extract_pieces!(knights & black, 1, 6, rgsq_black);
        extract_pieces!(pawns & white,   0, 0, rgsq_white);
        extract_pieces!(pawns & black,   0, 5, rgsq_black);

        let (hash, inverted) = build_config_hash(&rgi_counters);

        let sq_enp = if ep_square < 64 {
            ep_square as u32
        } else {
            XX
        };

        // Determine side for lookup
        let side = if !inverted {
            if wtm { 0usize } else { 1 }
        } else {
            if wtm { 1 } else { 0 }
        };

        // Get psqW, psqB (the "stronger" side's pieces are W)
        let (psq_w, psq_b) = if inverted {
            (&rgsq_black, &rgsq_white)
        } else {
            (&rgsq_white, &rgsq_black)
        };

        // Build piece type lists on the stack (no allocation)
        // Order: descending by value (Q=5, R=4, B=3, N=2, P=1)
        let (first, second) = if inverted { (5usize, 0usize) } else { (0, 5) };
        let mut w_pieces_buf = [0usize; 4];
        let mut b_pieces_buf = [0usize; 4];
        let mut nw = 0usize;
        let mut nb = 0usize;
        let order = [4usize, 3, 2, 1, 0]; // Q, R, B, N, P → piece types 5,4,3,2,1
        for &i in &order {
            for _ in 0..rgi_counters[first + i] {
                if nw < 4 { w_pieces_buf[nw] = i + 1; nw += 1; }
            }
        }
        for &i in &order {
            for _ in 0..rgi_counters[second + i] {
                if nb < 4 { b_pieces_buf[nb] = i + 1; nb += 1; }
            }
        }
        let w_pieces_cfg = &w_pieces_buf[..nw];
        let b_pieces_cfg = &b_pieces_buf[..nb];

        let sqwk = psq_w[5 * C_PIECES];
        let sqbk = psq_b[5 * C_PIECES];

        let f_invert = inverted;

        // Determine if the table is symmetric (only WTM file exists).
        // Must check before computing the index, since symmetric BTM needs swapped colors.
        let state = self.state.lock().unwrap();
        let table_entry = state.tables.get(&hash).ok_or(NalimovError::PositionNotFound)?;
        let lookup_side = if !table_entry[side].is_empty() {
            side
        } else if !table_entry[1 - side].is_empty() {
            1 - side
        } else {
            return Err(NalimovError::PositionNotFound);
        };
        drop(state);

        // For symmetric endgames probed as BTM, use IndCalcBF:
        // call the WTM index function with colors swapped and fInvert flipped.
        let index = if lookup_side != side {
            // Symmetric fallback: swap white ↔ black, flip invert, use WTM calc
            self.calc_index(
                b_pieces_cfg,
                w_pieces_cfg,
                psq_b,
                psq_w,
                sqbk,
                sqwk,
                sq_enp,
                !f_invert,
                true, // always WTM for symmetric lookup
            )?
        } else {
            self.calc_index(
                w_pieces_cfg,
                b_pieces_cfg,
                psq_w,
                psq_b,
                sqwk,
                sqbk,
                sq_enp,
                f_invert,
                side == 0,
            )?
        };

        if index == u64::MAX {
            return Err(NalimovError::PositionNotFound);
        }

        // Determine block number and offset within block.
        // 16-bit tables store 2 bytes per position, so each 8KB block holds 4096 positions.
        // 8-bit tables store 1 byte per position, 8192 positions per block.
        let mut state = self.state.lock().unwrap();

        let table_entry = state.tables.get(&hash).ok_or(NalimovError::PositionNotFound)?;
        let extents = &table_entry[lookup_side];
        if extents.is_empty() {
            return Err(NalimovError::PositionNotFound);
        }

        // Check if any extent in this table is 16-bit (they all share the same flag)
        let is_16bit = extents.values().next().map_or(false, |f| f.is_16bit);

        let (logical_block, offset_in_block) = if is_16bit {
            // 16-bit: 4096 positions per 8KB block, 2 bytes each
            let block = (index >> 12) as usize;
            let offset = ((index & 0xFFF) * 2) as usize;
            (block, offset)
        } else {
            // 8-bit: 8192 positions per 8KB block, 1 byte each
            let block = (index >> 13) as usize;
            let offset = (index & 0x1FFF) as usize;
            (block, offset)
        };

        let (extent_idx, physical_block) = if extents.len() > 1 {
            // Split table: extent = logical_block >> 18 (each extent covers 2GB)
            let ext = logical_block >> 18;
            (ext, logical_block - (ext << 18))
        } else {
            (0, logical_block)
        };

        // Check block cache first
        let cache_key = (hash, lookup_side as u8, extent_idx, physical_block);
        if let Some(cached) = state.cache.get(&cache_key) {
            let score = read_score_from_block(cached, offset_in_block, is_16bit);
            match score {
                None => return Err(NalimovError::PositionNotFound),
                Some(s) if s == L_BEV_BROKEN => return Err(NalimovError::PositionNotFound),
                Some(s) => return Ok(score_to_result(s)),
            }
        }

        // Cache miss — need to read from disk
        let table_entry = state.tables.get_mut(&hash).ok_or(NalimovError::PositionNotFound)?;
        let tb_file = table_entry[lookup_side]
            .get_mut(&extent_idx)
            .ok_or(NalimovError::PositionNotFound)?;

        // Lazily load decode_info (file header) on first access
        if tb_file.decode_info.is_none() {
            let info = comp_open_from_file(&tb_file.path)
                .map_err(NalimovError::DecompressError)?;
            tb_file.decode_info = Some(Arc::new(info));
        }
        let decode_info = Arc::clone(tb_file.decode_info.as_ref().unwrap());
        let path = tb_file.path.clone();

        // Drop the lock while doing disk I/O
        drop(state);

        let block_data = decompress_block_from_file(&decode_info, &path, physical_block)
            .map_err(NalimovError::DecompressError)?;

        let score = read_score_from_block(&block_data, offset_in_block, is_16bit);

        // Re-acquire lock to store in cache
        let mut state = self.state.lock().unwrap();
        state.cache.put(cache_key, block_data);

        match score {
            None => Err(NalimovError::PositionNotFound),
            Some(s) if s == L_BEV_BROKEN => Err(NalimovError::PositionNotFound),
            Some(s) => Ok(score_to_result(s)),
        }
    }

    /// Calculate the tablebase index for a position.
    #[allow(clippy::too_many_arguments)]
    fn calc_index(
        &self,
        w_pieces: &[usize],
        b_pieces: &[usize],
        psq_w: &[u32],
        psq_b: &[u32],
        sqwk: u32,
        sqbk: u32,
        sq_enp: u32,
        f_invert: bool,
        is_wtm: bool,
    ) -> Result<u64, NalimovError> {
        let nw = w_pieces.len();
        let nb = b_pieces.len();

        // Helper to get squares from psq array given piece type
        // psq layout: [pi_idx * C_PIECES + occurrence]
        // pieces are sorted desc, but psq is indexed by piece type
        // We need to map from the config's piece list to actual squares

        match (nw, nb) {
            (1, 0) => {
                // T21: KXK
                let pi1 = w_pieces[0];
                let sq1 = psq_w[(pi1 - 1) * C_PIECES];
                if is_wtm {
                    Ok(ind_calc_t21_w(pi1, sqwk, sq1, sqbk, f_invert))
                } else {
                    Ok(ind_calc_t21_b(pi1, sqwk, sq1, sqbk, f_invert))
                }
            }
            (1, 1) => {
                // T22: KXKY
                let piw1 = w_pieces[0];
                let pib1 = b_pieces[0];
                let sqw1 = psq_w[(piw1 - 1) * C_PIECES];
                let sqb1 = psq_b[(pib1 - 1) * C_PIECES];
                if is_wtm {
                    Ok(ind_calc_t22_w(piw1, pib1, sqwk, sqw1, sqbk, sqb1, sq_enp, f_invert))
                } else {
                    Ok(ind_calc_t22_b(piw1, pib1, sqwk, sqw1, sqbk, sqb1, sq_enp, f_invert))
                }
            }
            (2, 0) => {
                // T31: KXYK
                let piw1 = w_pieces[0];
                let piw2 = w_pieces[1];
                let (sqw1, sqw2) = get_two_squares(psq_w, piw1, piw2);
                if is_wtm {
                    Ok(ind_calc_t31_w(piw1, piw2, sqwk, sqw1, sqw2, sqbk, f_invert))
                } else {
                    Ok(ind_calc_t31_b(piw1, piw2, sqwk, sqw1, sqw2, sqbk, f_invert))
                }
            }
            (2, 1) => {
                // T32: KXYKZ
                let piw1 = w_pieces[0];
                let piw2 = w_pieces[1];
                let pib1 = b_pieces[0];
                let (sqw1, sqw2) = get_two_squares(psq_w, piw1, piw2);
                let sqb1 = psq_b[(pib1 - 1) * C_PIECES];
                if is_wtm {
                    Ok(ind_calc_t32_w(
                        piw1, piw2, pib1, sqwk, sqw1, sqw2, sqbk, sqb1, sq_enp, f_invert,
                    ))
                } else {
                    Ok(ind_calc_t32_b(
                        piw1, piw2, pib1, sqwk, sqw1, sqw2, sqbk, sqb1, sq_enp, f_invert,
                    ))
                }
            }
            (3, 0) => {
                // T41: KXYZK
                let piw1 = w_pieces[0];
                let piw2 = w_pieces[1];
                let piw3 = w_pieces[2];
                let (sqw1, sqw2, sqw3) = get_three_squares(psq_w, piw1, piw2, piw3);
                if is_wtm {
                    Ok(ind_calc_t41_w(
                        piw1, piw2, piw3, sqwk, sqw1, sqw2, sqw3, sqbk, f_invert,
                    ))
                } else {
                    Ok(ind_calc_t41_b(
                        piw1, piw2, piw3, sqwk, sqw1, sqw2, sqw3, sqbk, f_invert,
                    ))
                }
            }
            (3, 1) => {
                // T42: KXYZKA
                let piw1 = w_pieces[0];
                let piw2 = w_pieces[1];
                let piw3 = w_pieces[2];
                let pib1 = b_pieces[0];
                let (sqw1, sqw2, sqw3) = get_three_squares(psq_w, piw1, piw2, piw3);
                let sqb1 = psq_b[(pib1 - 1) * C_PIECES];
                if is_wtm {
                    Ok(ind_calc_t42_w(
                        piw1, piw2, piw3, pib1, sqwk, sqw1, sqw2, sqw3, sqbk, sqb1, sq_enp,
                        f_invert,
                    ))
                } else {
                    Ok(ind_calc_t42_b(
                        piw1, piw2, piw3, pib1, sqwk, sqw1, sqw2, sqw3, sqbk, sqb1, sq_enp,
                        f_invert,
                    ))
                }
            }
            (2, 2) => {
                // T33: KXYKAB
                let piw1 = w_pieces[0];
                let piw2 = w_pieces[1];
                let pib1 = b_pieces[0];
                let pib2 = b_pieces[1];
                let (sqw1, sqw2) = get_two_squares(psq_w, piw1, piw2);
                let (sqb1, sqb2) = get_two_squares(psq_b, pib1, pib2);
                if is_wtm {
                    Ok(ind_calc_t33_w(
                        piw1, piw2, pib1, pib2, sqwk, sqw1, sqw2, sqbk, sqb1, sqb2, sq_enp,
                        f_invert,
                    ))
                } else {
                    Ok(ind_calc_t33_b(
                        piw1, piw2, pib1, pib2, sqwk, sqw1, sqw2, sqbk, sqb1, sqb2, sq_enp,
                        f_invert,
                    ))
                }
            }
            _ => Err(NalimovError::PositionNotFound),
        }
    }
}

/// Get two piece squares from psq array, handling same/different piece types.
fn get_two_squares(psq: &[u32], pi1: usize, pi2: usize) -> (u32, u32) {
    if pi1 == pi2 {
        let base = (pi1 - 1) * C_PIECES;
        (psq[base], psq[base + 1])
    } else {
        (psq[(pi1 - 1) * C_PIECES], psq[(pi2 - 1) * C_PIECES])
    }
}

/// Get three piece squares from psq array.
fn get_three_squares(psq: &[u32], pi1: usize, pi2: usize, pi3: usize) -> (u32, u32, u32) {
    if pi1 == pi2 && pi2 == pi3 {
        let base = (pi1 - 1) * C_PIECES;
        (psq[base], psq[base + 1], psq[base + 2])
    } else if pi1 == pi2 {
        let base = (pi1 - 1) * C_PIECES;
        (psq[base], psq[base + 1], psq[(pi3 - 1) * C_PIECES])
    } else if pi2 == pi3 {
        let base = (pi2 - 1) * C_PIECES;
        (psq[(pi1 - 1) * C_PIECES], psq[base], psq[base + 1])
    } else {
        (
            psq[(pi1 - 1) * C_PIECES],
            psq[(pi2 - 1) * C_PIECES],
            psq[(pi3 - 1) * C_PIECES],
        )
    }
}

/// Read a score from a decompressed block.
/// For 8-bit tables: reads 1 byte, applies s_to_l conversion.
/// For 16-bit tables: reads 2 bytes (little-endian signed), returns directly.
fn read_score_from_block(block: &[u8], offset: usize, is_16bit: bool) -> Option<i32> {
    if is_16bit {
        if offset + 1 >= block.len() {
            return None;
        }
        let lo = block[offset] as i32;
        let hi = (block[offset + 1] as i8) as i32; // sign-extend high byte
        Some((hi << 8) + lo)
    } else {
        if offset >= block.len() {
            return None;
        }
        let raw = block[offset] as i8;
        Some(s_to_l(raw))
    }
}

/// Convert a DTM score to NalimovResult.
///
/// Nalimov L-score encoding:
///   Win:  L_score = L_BEV_BROKEN (32767) - DTM_moves  →  DTM_moves = 32767 - L_score
///   Loss: L_score = -(L_BEV_BROKEN - DTM_moves)       →  DTM_moves = 32767 + L_score
///
/// Conversion to plies (half-moves):
///   Win:  plies = 2 * DTM_moves - 1  (winning side delivers the last move)
///   Loss: plies = 2 * DTM_moves      (opponent delivers the mating move)
fn score_to_result(score: i32) -> NalimovResult {
    if score == 0 {
        NalimovResult::Draw
    } else if score > 0 {
        // Side to move wins in DTM_moves full moves
        let moves = (L_BEV_BROKEN - score) as u16;
        NalimovResult::Win { plies: 2 * moves - 1 }
    } else {
        // Side to move loses in DTM_moves full moves
        // plies = 2 * moves - 2 (opponent delivers the mating move)
        let moves = (L_BEV_BROKEN + score) as u16;
        NalimovResult::Loss { plies: 2 * moves - 2 }
    }
}

