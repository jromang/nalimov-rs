// Score constants from egtb.cpp
const PAGE_L: i32 = 256;
const TBBE_SSL: i32 = (PAGE_L - 4) / 2; // 126
const BEV_BROKEN: i32 = TBBE_SSL + 1; // 127
const BEV_LI0: i32 = -TBBE_SSL; // -126
const BEV_LIMAXX: i32 = -TBBE_SSL - 1; // -127

const L_PAGE_L: i32 = 65536;
const L_TBBE_SSL: i32 = (L_PAGE_L - 4) / 2; // 32766
const L_BEV_BROKEN: i32 = L_TBBE_SSL + 1; // 32767

const XX: u32 = 127;
const C_PIECES: usize = 3;

// Sentinel for king tables
const INF: i16 = 4000;

// Infinities for enumeration overflow
const INF_SINGLE: u32 = 110000;
const INF_PAIR: u32 = 6500000;
const INF_TRIPLE: u32 = 500000000;

/// Convert 8-bit tablebase score to 16-bit (L) score.
fn s_to_l(tbt: i8) -> i32 {
    let t = tbt as i32;
    if t == 0 {
        0
    } else if t > 0 {
        if t != BEV_BROKEN {
            t + 32640
        } else {
            L_BEV_BROKEN
        }
    } else if t >= BEV_LI0 {
        t - 32640
    } else if t == BEV_LIMAXX {
        -32640
    } else {
        // bev_miminx
        32640
    }
}

